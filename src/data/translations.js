/**
 * Returns a translated string for a given key path (e.g. 'nav.home', 'actions.search').
 * If missing, falls back to the English string or provided fallback.
 */
export function getTranslation(lang, keyPath, fallback = '') {
  const currentLang = lang === 'hi' ? 'hi' : 'en'
  const keys = keyPath.split('.')

  let obj = translations[currentLang]
  for (const k of keys) {
    if (obj && typeof obj === 'object' && k in obj) {
      obj = obj[k]
    } else {
      obj = undefined
      break
    }
  }

  if (obj !== undefined && typeof obj === 'string') {
    return obj
  }

  // Fallback to English
  let enObj = translations.en
  for (const k of keys) {
    if (enObj && typeof enObj === 'object' && k in enObj) {
      enObj = enObj[k]
    } else {
      enObj = undefined
      break
    }
  }

  if (enObj !== undefined && typeof enObj === 'string') {
    return enObj
  }

  return fallback || keyPath
}
